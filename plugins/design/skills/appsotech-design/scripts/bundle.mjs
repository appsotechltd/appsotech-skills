#!/usr/bin/env node
// Generates the single-file portable copy of this skill.
//
//   bundle.mjs -o dist/appsotech-design.md
//   bundle.mjs -o dist/appsotech-design.md --check
//
// The skill is a directory for good reasons: SKILL.md stays small and the
// references are read only when they apply, so asking for a button does not
// load the Flutter theming guide. This produces the other thing — one file to
// paste or drop somewhere that has no plugin manager, no shell and no way to
// copy a tree.
//
// What the bundle CANNOT carry is the scripts, and they are the difference
// between this skill and generic design advice. The bundle says so in its own
// header and routes the reader to the by-hand checklist, which the skill
// already documents for the no-filesystem case.
//
// --check is in the test suite for the tokens.dart reason: a generated file
// nobody regenerates is a stale file that looks authoritative.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const ROOT = join(import.meta.dirname, '..');

// Reference order follows the phases, so the bundle reads as one document
// rather than a directory listing in alphabetical order.
export const ORDER = [
  'design-phase.md',
  'style-directions.md',
  'design-tokens.md',
  'archetypes.md',
  'patterns-web.md',
  'patterns-mobile.md',
  'motion.md',
  'hero.md',
  'design-gate.md',
];

export function splitFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) return { frontmatter: null, body: text };
  return { frontmatter: m[1], body: m[2] };
}

const HEADER = `> **Single-file copy.** This is \`appsotech-design\` flattened into one
> document: the skill followed by all nine references, in phase order.
>
> **The scripts are not here and cannot be.** \`gate.mjs\`, \`contrast.mjs\`,
> \`audit-markup.mjs\`, \`responsive-check.mjs\`, \`tokens-dart.mjs\`,
> \`freeze-check.mjs\` and \`consistency.mjs\` are executable files, so every
> \`[auto]\` item in the gate becomes a by-hand check here — the skill's
> "No filesystem" section is written for exactly this case. The palettes in
> Style directions are pre-verified, so those numbers need not be recomputed.
>
> For the full skill including the gate, install the directory:
> \`\`\`
> git clone https://github.com/appsotechltd/appsotech-skills
> cp -r appsotech-skills/plugins/design/skills/appsotech-design ~/.claude/skills/
> \`\`\`
>
> Generated by \`scripts/bundle.mjs\` — do not edit by hand.`;

export function buildBundle() {
  const skill = readFileSync(join(ROOT, 'SKILL.md'), 'utf8');
  const { frontmatter, body } = splitFrontmatter(skill);
  if (!frontmatter) throw new Error('SKILL.md has no frontmatter');

  const parts = [`---\n${frontmatter}\n---\n`, HEADER, '\n'];
  // Names the reader will meet as `references/x.md` inside the text, mapped to
  // where they now live, so a cross-reference is followable rather than dead.
  parts.push('\n## What is in this file\n');
  parts.push('\n| Referred to as | Section below |\n|---|---|\n');
  for (const f of ORDER) {
    const title = readFileSync(join(ROOT, 'references', f), 'utf8')
      .split('\n')[0].replace(/^#\s*/, '');
    parts.push(`| \`references/${f}\` | ${title} |\n`);
  }
  parts.push('\n---\n\n');
  parts.push(body.trim());

  for (const f of ORDER) {
    const text = readFileSync(join(ROOT, 'references', f), 'utf8').trim();
    // Demote one level so the reference titles sit under the skill rather
    // than competing with it, and the document has one h1.
    const demoted = text.replace(/^(#+) /gm, '#$1 ');
    parts.push(`\n\n---\n\n<!-- references/${f} -->\n\n${demoted}`);
  }
  return `${parts.join('')}\n`;
}

// --- cli --------------------------------------------------------------------

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop());
if (isMain) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const oIdx = args.findIndex((a) => a === '-o' || a === '--out');
  const out = oIdx !== -1 ? args[oIdx + 1] : null;

  if (!out) {
    console.error('usage: bundle.mjs -o <dist/appsotech-design.md> [--check]');
    process.exit(2);
  }

  const bundle = buildBundle();

  if (check) {
    if (!existsSync(out)) {
      console.error(`${out} does not exist — run without --check to generate it.`);
      process.exit(1);
    }
    if (readFileSync(out, 'utf8').trimEnd() !== bundle.trimEnd()) {
      console.error(
        `${out} has drifted from the skill.\n` +
        'Regenerate it. The directory is the master and the bundle is the copy.');
      process.exit(1);
    }
    console.log(`${out} matches the skill — ${bundle.split('\n').length} lines.`);
    process.exit(0);
  }

  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, bundle);
  console.log(`${out} written — ${bundle.split('\n').length} lines, ${ORDER.length} references inlined.`);
}
